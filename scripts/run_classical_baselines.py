from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

from ampere.evaluation.leaderboard import rank_leaderboard
from ampere.evaluation.metrics import evaluate_predictions
from ampere.reconstruction.baselines import BASELINE_SPECS, DEFAULT_METHODS
from ampere.reconstruction.classical import load_canonical_long, run_classical_methods, write_predictions
from ampere.reconstruction.interpolation import pchip_status
from ampere.utils.paths import as_repo_relative
from ampere.visualization.plots import generate_classical_plots


DATASET_INPUTS = {
    "rlc_sample": "rlc_sample_long.parquet",
    "appliance_8ch": "appliance_8ch_long.parquet",
}

PREDICTION_NAMES = {
    "rlc_sample": "rlc_sample_classical_predictions",
    "appliance_8ch": "appliance_8ch_classical_predictions",
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Run AMPERE classical reconstruction baselines.")
    parser.add_argument(
        "--datasets",
        nargs="+",
        choices=sorted(DATASET_INPUTS),
        default=sorted(DATASET_INPUTS),
        help="Canonical datasets to evaluate.",
    )
    parser.add_argument(
        "--methods",
        nargs="+",
        default=DEFAULT_METHODS,
        help="Methods to run. Defaults to all classical baselines.",
    )
    parser.add_argument(
        "--processed-dir",
        type=Path,
        default=ROOT / "outputs" / "data" / "processed",
        help="Directory containing Phase 1 canonical outputs.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=ROOT / "outputs" / "reconstruction" / "classical",
        help="Directory for prediction and leaderboard outputs.",
    )
    parser.add_argument(
        "--figures-dir",
        type=Path,
        default=ROOT / "outputs" / "figures" / "classical",
        help="Directory for lightweight diagnostic plots.",
    )
    parser.add_argument(
        "--report-path",
        type=Path,
        default=ROOT / "reports" / "classical_baseline_report.md",
        help="Markdown report path.",
    )
    parser.add_argument("--skip-plots", action="store_true", help="Skip figure generation.")
    return parser.parse_args()


def format_value(value: Any) -> str:
    if pd.isna(value):
        return ""
    if isinstance(value, float):
        if abs(value) >= 1000 or (0 < abs(value) < 0.001):
            return f"{value:.4e}"
        return f"{value:.4f}"
    return str(value)


def markdown_table(df: pd.DataFrame, columns: list[str], max_rows: int | None = None) -> list[str]:
    if df.empty:
        return ["_No rows._"]
    table = df[columns].copy()
    if max_rows is not None:
        table = table.head(max_rows)
    lines = [
        "| " + " | ".join(columns) + " |",
        "| " + " | ".join(["---"] * len(columns)) + " |",
    ]
    for row in table.itertuples(index=False):
        lines.append("| " + " | ".join(format_value(value) for value in row) + " |")
    return lines


def run_one_dataset(
    dataset_id: str,
    *,
    processed_dir: Path,
    output_dir: Path,
    methods: list[str],
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, dict[str, Any]]:
    input_path = processed_dir / DATASET_INPUTS[dataset_id]
    canonical = load_canonical_long(input_path)
    result = run_classical_methods(canonical, methods=methods)

    output_dir.mkdir(parents=True, exist_ok=True)
    prediction_meta = write_predictions(
        result.predictions,
        output_dir / PREDICTION_NAMES[dataset_id],
    )
    metrics = evaluate_predictions(result.predictions)
    leaderboard = rank_leaderboard(metrics.overall)

    dataset_meta = {
        "dataset_id": dataset_id,
        "input_path": as_repo_relative(input_path, ROOT),
        "input_rows": int(len(canonical)),
        "input_columns": int(len(canonical.columns)),
        "prediction_output": {
            **prediction_meta,
            "path": as_repo_relative(prediction_meta["path"], ROOT),
        },
        "method_metadata": result.method_metadata,
    }
    return result.predictions, leaderboard, metrics.branch, dataset_meta


def write_report(
    *,
    report_path: Path,
    datasets: list[dict[str, Any]],
    leaderboard: pd.DataFrame,
    branch_metrics: pd.DataFrame,
    figure_paths: list[str],
    output_paths: dict[str, str],
) -> None:
    report_path.parent.mkdir(parents=True, exist_ok=True)
    pchip = pchip_status()

    lines = [
        "# Classical Baseline Report",
        "",
        "Generated by `python scripts/run_classical_baselines.py --datasets rlc_sample appliance_8ch`.",
        "",
        "## Scope",
        "",
        "This Stage 1 / Phase 2 run evaluates classical sparse-to-dense reconstruction baselines only. No RF, boosting, neural, physics-guided, or RL models were trained or implemented.",
        "",
        "All inputs were Phase 1 canonical outputs under `outputs/data/processed`. Raw files under `Data/` were not used as baseline inputs and were not modified.",
        "",
        "## Datasets Evaluated",
        "",
    ]
    for item in datasets:
        lines.append(
            f"- `{item['dataset_id']}`: `{item['input_path']}` ({item['input_rows']} long rows x {item['input_columns']} columns)"
        )
    lines.extend(
        [
            "",
            "## Methods",
            "",
        ]
    )
    for method in DEFAULT_METHODS:
        spec = BASELINE_SPECS[method]
        lines.append(f"- `{method}`: {spec.description} Edge policy: {spec.edge_policy}")
    lines.extend(
        [
            "",
            f"PCHIP availability: `{pchip.available}` ({pchip.reason}).",
            "",
            "The `slope_aware_an` method is a practical AN-style baseline, not a claim of reproducing a legacy formula. It estimates local slopes from neighboring observed points, zeros slopes at sign-changing extrema, clamps slopes to avoid large overshoot, evaluates a cubic Hermite segment, and clips each segment to the observed endpoint range.",
            "",
            "## Leaderboard",
            "",
        ]
    )
    leaderboard_cols = [
        "dataset_id",
        "rank",
        "method",
        "mae",
        "rmse",
        "median_abs_error",
        "weighted_energy_error",
        "dwell_mae",
        "observed_point_mae",
        "unobserved_point_mae",
        "abs_energy_error_Wh_sum",
    ]
    lines.extend(markdown_table(leaderboard, leaderboard_cols))
    winner_rows = []
    for dataset_id, group in leaderboard.groupby("dataset_id", sort=False):
        by_mae = group.sort_values("mae").iloc[0]
        by_energy = group.sort_values("weighted_energy_error").iloc[0]
        by_dwell = group.sort_values("dwell_mae").iloc[0]
        winner_rows.append(
            {
                "dataset_id": dataset_id,
                "best_mae_method": by_mae["method"],
                "best_weighted_energy_method": by_energy["method"],
                "best_dwell_mae_method": by_dwell["method"],
            }
        )
    lines.extend(
        [
            "",
            "## Interpretation And Cautions",
            "",
        ]
    )
    lines.extend(
        markdown_table(
            pd.DataFrame(winner_rows),
            ["dataset_id", "best_mae_method", "best_weighted_energy_method", "best_dwell_mae_method"],
        )
    )
    lines.extend(
        [
            "",
            "- The RLC leaderboard is sample-level `raw_signed_power`. `mean_per_branch` winning MAE is a caution, not a proof that it is a useful online reconstruction policy; reactive signed branches are near sign-symmetric and can reward mean-like behavior.",
            "- On `rlc_sample`, ZOH has worse MAE but the best clipped-nonnegative diagnostic energy error. This reinforces that metric choice must stay tied to the declared power representation.",
            "- On `appliance_8ch`, ZOH has the best pointwise MAE, while mean-per-branch has the lowest signed weighted energy error. Energy totals can hide transition/timing errors.",
            "- Observed-point MAE is zero for every method because each baseline explicitly preserves the measured `P_observed` values at observed timestamps.",
        ]
    )
    lines.extend(
        [
            "",
            "## Per-Branch Results",
            "",
        ]
    )
    branch_cols = [
        "dataset_id",
        "method",
        "branch_id",
        "branch_name",
        "mae",
        "rmse",
        "abs_energy_error_Wh",
        "dwell_mae",
        "observed_point_mae",
        "unobserved_point_mae",
        "branch_negative_fraction",
        "branch_negative_energy_fraction",
    ]
    branch_table = branch_metrics.sort_values(["dataset_id", "method", "branch_id"])
    lines.extend(markdown_table(branch_table, branch_cols, max_rows=100))
    lines.extend(
        [
            "",
            "## Energy Metrics",
            "",
            "Signed energy is computed as `sum(P * dt_s) / 3600` in Wh. `weighted_energy_error` is `sum_b abs(E_hat_b - E_true_b) / (epsilon + sum_b abs(E_true_b))`.",
            "",
        ]
    )
    energy_cols = [
        "dataset_id",
        "rank",
        "method",
        "E_true_signed_Wh_sum",
        "E_hat_signed_Wh_sum",
        "abs_energy_error_Wh_sum",
        "weighted_energy_error",
        "weighted_energy_error_clipped_nonnegative_diagnostic",
    ]
    lines.extend(markdown_table(leaderboard, energy_cols))
    lines.extend(
        [
            "",
            "## Dwell/Window Metrics",
            "",
            "Dwell metrics average `P_true` and `P_hat` inside each canonical `dwell_id`, then score the dwell-level means and dwell-level signed energy.",
            "",
        ]
    )
    dwell_cols = [
        "dataset_id",
        "rank",
        "method",
        "dwell_mae",
        "dwell_abs_energy_error_Wh_total",
    ]
    lines.extend(markdown_table(leaderboard, dwell_cols))
    lines.extend(
        [
            "",
            "## Semantics Notes",
            "",
            "- Results use `raw_signed_power`; RLC negative values are structural and are not clipped.",
            "- `P_clipped_nonnegative` appears only in explicitly named diagnostic energy metrics.",
            "- The 8-channel component-circuit dataset uses corrected `dt_s = 0.04` from the time-major interleaved dense-truth layout.",
            "- Appliance native scan mask uses one 40 ms selected-branch row per dwell; 8-branch scan cycle = 0.32 s.",
            "",
            "## Generated Outputs",
            "",
        ]
    )
    for label, path in output_paths.items():
        lines.append(f"- `{label}`: `{path}`")
    for path in figure_paths:
        lines.append(f"- figure: `{as_repo_relative(path, ROOT)}`")
    lines.extend(
        [
            "",
            "## Recommended Next Phase",
            "",
            "Stage 2 RF/boosting baselines can start after reviewing this leaderboard, using these classical methods as the reference floor. Keep future online/offline feature availability explicit, especially if using `next_observed_value`.",
            "",
        ]
    )
    report_path.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    args = parse_args()
    all_predictions = []
    all_leaderboards = []
    all_branch_metrics = []
    dataset_reports: list[dict[str, Any]] = []

    for dataset_id in args.datasets:
        predictions, leaderboard, branch_metrics, dataset_meta = run_one_dataset(
            dataset_id,
            processed_dir=args.processed_dir,
            output_dir=args.output_dir,
            methods=args.methods,
        )
        all_predictions.append(predictions)
        all_leaderboards.append(leaderboard)
        all_branch_metrics.append(branch_metrics)
        dataset_reports.append(dataset_meta)

    combined_predictions = pd.concat(all_predictions, ignore_index=True)
    combined_leaderboard = pd.concat(all_leaderboards, ignore_index=True)
    combined_branch_metrics = pd.concat(all_branch_metrics, ignore_index=True)

    args.output_dir.mkdir(parents=True, exist_ok=True)
    leaderboard_csv = args.output_dir / "classical_leaderboard.csv"
    leaderboard_json = args.output_dir / "classical_leaderboard.json"
    branch_metrics_csv = args.output_dir / "classical_branch_metrics.csv"
    combined_leaderboard.to_csv(leaderboard_csv, index=False)
    combined_leaderboard.to_json(leaderboard_json, orient="records", indent=2)
    combined_branch_metrics.to_csv(branch_metrics_csv, index=False)

    figure_paths: list[str] = []
    if not args.skip_plots:
        figure_paths = generate_classical_plots(
            predictions=combined_predictions,
            leaderboard=combined_leaderboard,
            branch_metrics=combined_branch_metrics,
            output_dir=args.figures_dir,
        )

    output_paths = {
        "classical_leaderboard.csv": as_repo_relative(leaderboard_csv, ROOT),
        "classical_leaderboard.json": as_repo_relative(leaderboard_json, ROOT),
        "classical_branch_metrics.csv": as_repo_relative(branch_metrics_csv, ROOT),
    }
    for dataset_meta in dataset_reports:
        output_paths[f"{dataset_meta['dataset_id']}_predictions"] = dataset_meta["prediction_output"]["path"]

    write_report(
        report_path=args.report_path,
        datasets=dataset_reports,
        leaderboard=combined_leaderboard,
        branch_metrics=combined_branch_metrics,
        figure_paths=figure_paths,
        output_paths=output_paths,
    )

    summary = {
        "status": "ok",
        "datasets": dataset_reports,
        "outputs": output_paths,
        "figures": [as_repo_relative(path, ROOT) for path in figure_paths],
        "leaderboard": combined_leaderboard[
            ["dataset_id", "rank", "method", "mae", "weighted_energy_error", "dwell_mae"]
        ].to_dict(orient="records"),
    }
    print(json.dumps(summary, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
